// Generates src/types/mechfight.ts strictly from schema/mechfight.schema.json. Never hand-edit the output.
//   npm run gen:types                    (uses the committed schema copy)
//   npm run gen:types -- --from-kit      (first refreshes the copy from _kit/mechfight.schema.json)
import { compile } from "json-schema-to-typescript"
import { copyFileSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const schemaPath = resolve(root, "schema/mechfight.schema.json")
const outPath = resolve(root, "src/types/mechfight.ts")

if (process.argv.includes("--from-kit")) {
  const kit = resolve(root, "_kit/mechfight.schema.json")
  if (!existsSync(kit)) throw new Error("--from-kit: _kit/mechfight.schema.json not found")
  copyFileSync(kit, schemaPath)
}

const schema = JSON.parse(readFileSync(schemaPath, "utf8"))
const ts = await compile(schema, "MechfightMessage", {
  bannerComment: "/* GENERATED by scripts/gen-types.mjs from schema/mechfight.schema.json. DO NOT EDIT. Run `npm run gen:types`. */",
  additionalProperties: false, // the schema never forbids extras; we simply do not want index signatures
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  strictIndexSignatures: false,
  format: false,
})
writeFileSync(outPath, ts.replace(/\r\n/g, "\n"))
console.error(`wrote ${outPath} (${ts.length} bytes)`)
